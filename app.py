import streamlit as st
from groq import Groq, APIConnectionError, APIStatusError
from groq import RateLimitError, AuthenticationError

st.set_page_config(page_title="AI Email Generator", page_icon="✉️")

st.title("✉️ AI Email Generator")
st.write("Generate professional emails using AI.")

try:
    api_key = st.secrets.get("GROQ_API_KEY", "")
except Exception:
    api_key = ""

if not api_key:
    st.error("Add GROQ_API_KEY to Streamlit Secrets.")
    st.stop()

client = Groq(api_key=api_key)

topic = st.text_input("Email topic")
recipient = st.text_input("Recipient")
purpose = st.text_area("Purpose and key details")

tone = st.selectbox(
    "Email tone",
    ["Professional", "Formal", "Friendly", "Persuasive", "Concise"]
)

length = st.selectbox(
    "Email length",
    ["Short", "Medium", "Detailed"]
)

if st.button("Generate Email", type="primary"):
    if not topic.strip() or not purpose.strip():
        st.warning("Enter the topic and purpose.")
    else:
        prompt = f"""
        Write a complete email.

        Topic: {topic}
        Recipient: {recipient or "Relevant recipient"}
        Purpose: {purpose}
        Tone: {tone}
        Length: {length}

        Include a suitable subject line.
        Keep the email natural and professional.
        Do not invent facts or qualifications.
        Return only the email draft.
        """

        try:
            with st.spinner("Generating email..."):
                response = client.chat.completions.create(
                    model="openai/gpt-oss-20b",
                    messages=[
                        {
                            "role": "system",
                            "content": "You are a professional email-writing assistant."
                        },
                        {"role": "user", "content": prompt}
                    ],
                    max_tokens=1200,
                    temperature=0.7
                )

            email = response.choices[0].message.content or ""

            if email.strip():
                st.subheader("Generated Email")
                st.text_area("Your email", email, height=350)
                st.download_button(
                    "Download Email",
                    email,
                    file_name="generated_email.txt"
                )
            else:
                st.warning("No email was returned. Please try again.")

        except AuthenticationError:
            st.error("Invalid Groq API key. Check your Secrets.")
        except RateLimitError:
            st.error("Groq usage limit reached. Check your account limits.")
        except APIConnectionError:
            st.error("Connection failed. Please try again.")
        except APIStatusError as e:
            st.error(f"Groq API error: HTTP {e.status_code}")
        except Exception:
            st.error("Something went wrong. Check your app configuration.")