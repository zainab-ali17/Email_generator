import streamlit as st
from openai import OpenAI

st.set_page_config(
    page_title="AI Email Generator",
    page_icon="✉️",
    layout="centered"
)

st.title("✉️ AI Email Generator")
st.write(
    "Generate professional, personalized emails "
    "in seconds using AI."
)

# Load the API key securely from Streamlit Secrets
api_key = st.secrets.get("OPENAI_API_KEY", "")

if not api_key:
    st.error(
        "OpenAI API key is missing. "
        "Add OPENAI_API_KEY to your Streamlit Secrets."
    )
    st.stop()

client = OpenAI(api_key=api_key)

# Email inputs
topic = st.text_input(
    "Email subject or topic",
    placeholder="e.g., Application for AI Engineer position"
)

recipient = st.text_input(
    "Who is the email for?",
    placeholder="e.g., Hiring Manager"
)

purpose = st.text_area(
    "What do you want to communicate?",
    placeholder="Describe the purpose and key details..."
)

col1, col2 = st.columns(2)

with col1:
    tone = st.selectbox(
        "Email tone",
        ["Professional", "Formal", "Friendly",
         "Persuasive", "Concise"]
    )

with col2:
    length = st.selectbox(
        "Email length",
        ["Short", "Medium", "Detailed"]
    )

generate = st.button(
    "Generate Email",
    type="primary",
    use_container_width=True
)

if generate:
    if not topic.strip() or not purpose.strip():
        st.warning(
            "Please enter the email topic and purpose."
        )
    else:
        prompt = f"""
        Write a complete email using these details:

        Topic: {topic}
        Recipient: {recipient or "Relevant recipient"}
        Purpose and key details: {purpose}
        Tone: {tone}
        Length: {length}

        Requirements:
        - Write a suitable subject line.
        - Use a clear and professional structure.
        - Keep the message natural and specific.
        - Do not invent qualifications, facts, or promises.
        - Return only the email draft.
        """

        try:
            with st.spinner("Generating your email..."):
                response = client.responses.create(
                    model="gpt-4o-mini",
                    input=prompt
                )

            email = response.output_text

            st.subheader("Generated Email")
            st.text_area(
                "Review and copy your email",
                value=email,
                height=350
            )

            st.download_button(
                "Download Email",
                data=email,
                file_name="generated_email.txt",
                mime="text/plain",
                use_container_width=True
            )

        except Exception as e:
            st.error(
                "Email generation failed. Check your API "
                "configuration and try again."
            )
            st.caption(f"Error details: {e}")